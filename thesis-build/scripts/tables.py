def _ja(text: str) -> str:
    return r"\ja{" + text + "}"


def keigo_lexicon() -> None:
    import ast
    k = _keigo()
    # frozensets lose the order of the source, which groups the spellings of a word
    source = ast.parse(Path(k.__file__).read_text(encoding="utf-8"))
    listed = {n.targets[0].id: [e.value for e in n.value.args[0].elts]
              for n in source.body if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name)
              and isinstance(n.value, ast.Call) and n.value.args and isinstance(n.value.args[0], ast.Set)}
    by_set = {frozenset(v): v for v in listed.values()}
    order = lambda forms: by_set.get(frozenset(forms), sorted(forms))
    rows = [("Respectful verbs (\\textit{sonkeigo})", k.SONKEIGO_LEMMAS,
             "honorific directed at the customer"),
            ("Humble verbs (\\textit{kenj\\=ogo})", k.KENJOUGO_LEMMAS,
             "honorific directed at the customer"),
            ("Polite auxiliaries (\\textit{teineigo})", k.TEINEIGO_AUX,
             "a polite sentence when it ends the sentence"),
            ("Plain auxiliaries", k.PLAIN_AUX, "a plain sentence, a defect"),
            ("Respect auxiliaries", k.RESPECT_AUX,
             "after a respectful verb, a double honorific, a defect"),
            ("Honorific prefix (\\textit{o-}, \\textit{go-})", k.HONORIFIC_PREFIX_LEMMAS,
             "density only")]
    body = [f"{name} & {_ja('、'.join(order(forms)))} & {role} \\\\" for name, forms, role in rows]
