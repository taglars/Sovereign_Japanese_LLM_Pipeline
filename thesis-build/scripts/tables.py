# ---- The rubric and the judge prompt, as sent --------------------

def _rubric_tex(text: str) -> str:
    """One line of rubric text as LaTeX: `field` in typewriter, -> as an arrow."""
    import re
    parts = text.split("`")
    out = []
    for i, part in enumerate(parts):
        s = part.replace("\\", r"\textbackslash{}")
        for a, b in (("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"),
                     ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"),
                     ("^", r"\textasciicircum{}")):
            s = s.replace(a, b)
        s = s.replace("->", r"$\rightarrow$")
        s = re.sub(r'"([^"]*)"', r"``\1''", s)
        out.append(r"\texttt{" + s + "}" if i % 2 else s)
    return "".join(out)


def _rubric_block(text: str) -> str:
    """The six aspects: heading, question, instructions, anchors, answer line."""
    import re
    lines, items = [], []

    def flush():
        if items:
            lines.append(r"\begin{description}")
            lines.extend(items)
            lines.append(r"\end{description}")
            items.clear()

    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue
        head = re.match(r"\*\*(\w+)\*\*\s*[,（]\s*(.*?)）?$", line)
        anchor = re.match(r"(\d+)\s*=\s*(.*)", line)
        if head:
            flush()
            lines.append(r"\paragraph{\texttt{" + _rubric_tex(head.group(1)) + "}: "
                         + _rubric_tex(head.group(2)) + "}")
        elif anchor:
            items.append(r"  \item[" + anchor.group(1) + "] " + _rubric_tex(anchor.group(2)))
        else:
            flush()
            lines.append(_rubric_tex(line) + r"\par")
    flush()
    return "\n".join(lines)


def _system_block(prompt: str) -> str:
    """The system message, with the JSON schema replaced by a pointer to its table."""
    system = prompt.split("===== SYSTEM =====", 1)[1].split("===== USER =====", 1)[0]
    lines, bullets = [], []

    def flush():
        if bullets:
            lines.append(r"\begin{itemize}")
            lines.extend(bullets)
            lines.append(r"\end{itemize}")
            bullets.clear()

    for raw in system.splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("<schema>"):
            flush()
            lines.append(r"\emph{[The output schema, as JSON, whose fields are listed in "
                         r"Table~\ref{tab:judge_schema}.]}\par")
        elif line.startswith("- "):
            bullets.append(r"  \item " + _rubric_tex(line[2:]))
        else:
            flush()
            lines.append(_rubric_tex(line) + r"\par")
    flush()
    return "\n".join(lines)


def _frame_block(prompt: str) -> str:
    """The user message after the rubric: customer data and the script, without its text."""
    user = prompt.split("===== USER =====", 1)[1]
    start = user.index("<customer_data>")
    head = user[start:user.index("<section label=", start)]
    tail = user[user.index("</script>"):]
    body = head.rstrip().splitlines() + ['<section label="...">', "[the text of one section]",
                                         "</section>", "[further sections]"] + tail.strip().splitlines()
    # tags and placeholders keep their own line; prose lines are joined and left to wrap
    out, para = [r"\begin{quote}\small\ttfamily\raggedright"], []

    def flush():
        if para:
            out.append(" ".join(para) + r"\\")
            para.clear()

    for line in body:
        line = line.replace('id="S01"', 'id="..."').strip()
        tex = _rubric_tex(line).replace("``", '"').replace("''", '"')
        if not line:
            flush()
            out.append(r"\\")
        elif line.startswith(("<", "[")) and line.endswith((">", "]")):
            flush()
            # {} keeps a leading [ from being read as the optional argument of the \\ before it
            out.append(("{}" if tex.startswith("[") else "") + tex + r"\\")
        else:
            para.append(tex)
    flush()
    out.append(r"\end{quote}")
    return "\n".join(out).replace(r"\\" + "\n" + r"\\", r"\\[0.6ex]")


