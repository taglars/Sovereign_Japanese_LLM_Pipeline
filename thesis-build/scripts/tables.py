def feedback_shares() -> None:
    from jv.codebook import BY_ID
    rep = json.loads((JV / "out" / "codebook" / "report.json").read_text())
    judges = ("deepseek-v4-flash", "glm-4.7-flash")
    cols = [("judge", j) for j in judges] + [("exp3_condition", f"{j}|{c}") for j in judges for c in ("en", "ja")]
    body = []
    for kind, title, prefix in (("strength", "Strengths", "S_"), ("weakness", "Weaknesses", "W_"),
                                ("gap", "Gaps", "G_")):
        if body:
            body.append(r"\addlinespace")
        body.append(rf"\multicolumn{{7}}{{@{{}}l}}{{\emph{{{title}}}}} \\")
        shares = [rep[view][kind]["shares"].get(key, {}) for view, key in cols]
        own = sorted((c for c in BY_ID if c.startswith(prefix)),
                     key=lambda c: -sum(shares[i].get(c, 0) for i in range(2)))
        for c in own:
            body.append(f"{_tex(BY_ID[c].label)} & " + " & ".join(f"{100 * s.get(c, 0):.1f}" for s in shares) + r" \\")
        body.append("Other & " + " & ".join(f"{100 * (1 - sum(s.get(c, 0) for c in own)):.1f}" for s in shares) + r" \\")
        counts = [sum(rep[view][kind]["counts"].get(key, {}).values()) for view, key in cols]
        body.append(r"\textit{Points} & " + " & ".join(f"{n:,}" for n in counts) + r" \\")
    _write("feedback_shares", _float(
        "Share of each judge's points per feedback category (\\%), for all scripts as in "
        "Figure~\\ref{fig:exp4_feedback} and for the scripts of Experiment~3 by the language of "
        "the instructions they were written from (EN, JA). Other collects the points the classifier "
        "filed under a category of another kind.", "tab:feedback_shares",
        r"@{}>{\raggedright\arraybackslash}p{4.4cm}rrrrrr@{}",
        r"& \multicolumn{2}{c}{All scripts} & \multicolumn{4}{c}{Experiment~3} \\"
        "\n    " r"\cmidrule(lr){2-3}\cmidrule(l){4-7}" "\n    "
        r"& & & \multicolumn{2}{c}{DeepSeek} & \multicolumn{2}{c}{GLM} \\" "\n    "
        r"\cmidrule(lr){4-5}\cmidrule(l){6-7}" "\n    "
        r"Category & DeepSeek & GLM & EN & JA & EN & JA", body, place="H"))


