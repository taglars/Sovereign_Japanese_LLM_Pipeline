    from results_macros import RATER_ORDER, rater_data
    from jv.human import load_all, range_usage
    d = rater_data()
    S, R, sp, cons = d["scripts"], d["raters"], d["spearman"], d["consensus"]
    usage = range_usage(load_all(d["arms"]))
    body = []
    for i, n in enumerate(RATER_ORDER, 1):
        u = usage[n]
        rest = cons([m for m in RATER_ORDER if m != n])
        rho = sp([R[n].overall[s] for s in S], [rest[s] for s in S])
