def _names() -> dict:
    return json.loads(NAMES.read_text(encoding="utf-8"))


def _anon(text: str) -> str:
    for a, b in _names()["replace"]:
        text = text.replace(a, b)
    return text


def _check_anon(text: str) -> str:
    left = [w for w in _names()["banned"] if w in text]
    assert not left, f"names left in an example: {left}"
    return text


def _latex(text: str) -> str:
    """Escape data text for LaTeX, in or outside a CJK block."""
    text = text.replace("\\", r"\textbackslash{}")
    for a, b in (("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"),
                 ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"),
                 ("^", r"\textasciicircum{}")):
        text = text.replace(a, b)
    text = text.replace("\\textbackslash\\{\\}", r"\textbackslash{}")
    # Markdown bold left in a script: allow a line break after it in Japanese text
    return text.replace("**", r"**\allowbreak{}")


def _mixed(text: str) -> str:
    """English text with Japanese quoted in it, each Japanese run in a CJK block."""
    import re
    cjk = r"[\u3000-\u30ff\u3400-\u9fff\uff00-\uffef\u25cb]+(?:[0-9A-Za-z.,%~\-/()（）＝:：\s]*[\u3000-\u30ff\u3400-\u9fff\uff00-\uffef\u25cb]+)*"
    parts, last = [], 0
    for m in re.finditer(cjk, text):
        parts.append(_latex(text[last:m.start()]))
        parts.append(_ja(_latex(m.group(0))))
        last = m.end()
    parts.append(_latex(text[last:]))
    return "".join(parts)


def _example_scripts() -> dict:
    corpus = json.loads((JV / "out" / "exp3" / "corpus.json").read_text(encoding="utf-8"))
    out = {}
    for script in corpus:
        if script["vin"] == EXAMPLE["customer"]:
            out[script["arm"].split("_")[-1]] = script
    assert set(out) == {"en", "ja"}, out.keys()
    return out


def _marked(html: str, scorer, k) -> str:
    """Section text with every counted respectful or humble form underlined."""
    lines = []
    for line in k.strip_html(_anon(html)).split("\n"):
        line = line.strip()
        if not line:
            continue
        words = []
        for w in scorer._tagger(line):
            lemma = w.feature.lemma or w.surface
            s = _latex(w.surface)
            if lemma in k.SONKEIGO_LEMMAS or lemma in k.KENJOUGO_LEMMAS:
                s = r"\underline{" + s + "}"
            words.append(w.white_space + s)
        lines.append("".join(words))
    return "\\par\n".join(lines)


def example() -> None:
    import sqlite3
    k = _keigo()
