def rubric() -> None:
    import jv.rubric as rb
    src = JV / "out"
    for lang in ("en", "ja"):
        prompt = (src / f"prompt_{lang}.txt").read_text(encoding="utf-8")
        cjk = (r"\begin{CJK}{UTF8}{min}", r"\end{CJK}")
        _write_raw(f"judge_system_{lang}", "\n".join(
            [cjk[0], _system_block(prompt), cjk[1]]))
        _write_raw(f"rubric_{lang}", "\n".join(
            [cjk[0], _rubric_block((src / f"rubric_{lang}.txt").read_text(encoding="utf-8")),
             cjk[1]]))
    _write_raw("judge_frame", _frame_block((src / "prompt_en.txt").read_text(encoding="utf-8")))
    props = rb.JSON_SCHEMA["properties"]
    what = {"keigo_errors": "honorific errors, each a quoted span and the problem",
            "generic_spans": "generic passages, each a quoted span and why",
            "missing_for_call": "facts the salesperson would miss for the call",
            "objections": "objections the customer would raise",
            "non_japanese_sections": "sections whose text is not Japanese",
            "has_cta": "whether the script asks for a next step",
            "notes": "free comment"}
    body = []
    for field in rb.JSON_SCHEMA["required"]:
        spec = props[field]
        kind = {"integer": "whole number, 1 to 10", "boolean": "true or false",
                "string": "text"}.get(spec["type"], f"list of up to {spec.get('maxItems')}")
        body.append(rf"\texttt{{{_rubric_tex(field)}}} & {kind} & "
                    + (what.get(field, "score") if not field.endswith("_score") else "score")
                    + r" \\")
    text = _float("The fields of the judge's answer, in the order the schema requires them. "
                  "Each list holds at most ten entries and comes before the score it "
                  "supports.", "tab:judge_schema", r"@{}llp{0.4\textwidth}@{}", "Field & Type & Content", body,
                  place="H")
    _write_raw("judge_schema", text)


