def _rows(name: str) -> list[dict]:
    with open(DATA / name, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def _tex(text: str) -> str:
    """Escape a data string for LaTeX; ranges get an en dash, no em dashes."""
    text = text.replace("—", "not recorded").replace("–", "--")
    text = text.replace("~", "about ")
    for a, b in (("%", r"\%"), ("&", r"\&"), ("_", r"\_")):
        text = text.replace(a, b)
    return text


def _p(p) -> str:
    return "n/a" if p is None else ("$<$0.001" if p < 0.001 else f"{p:.3f}")


def _float(caption: str, label: str, spec: str, header: str, body: list[str],
           note: str = "", place: str = "tb") -> str:
    lines = [f"\\begin{{table}}[{place}]", r"  \centering", r"  \small",
             r"  \setlength{\tabcolsep}{4pt}",
             f"  \\begin{{tabular}}{{{spec}}}", r"    \toprule", f"    {header} \\\\",
             r"    \midrule"]
    lines += [f"    {row}" for row in body]
    lines += [r"    \bottomrule", r"  \end{tabular}"]
    lines += [f"  \\caption{{{caption}{(' ' + note) if note else ''}}}", f"  \\label{{{label}}}",
              r"\end{table}"]
    return "\n".join(lines) + "\n"


def _minus(text: str) -> str:
    """A minus sign, not a hyphen, before negative numbers in table rows."""
    import re
    return re.sub(r"(?<![\w$\-])-(\d)", r"$-$\1", text)


def _write(name: str, text: str) -> None:
    text = "\n".join(_minus(line) if "&" in line else line for line in text.splitlines()) + "\n"
    OUT.mkdir(exist_ok=True)
    (OUT / f"{name}.tex").write_text(
        f"% Generated by scripts/tables.py. Do not edit by hand.\n{text}", encoding="utf-8")
    print(f"  tables/{name}.tex")


